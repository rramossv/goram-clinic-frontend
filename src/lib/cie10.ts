export function normalizar(texto: string) {
  return texto.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().trim()
}

const INDICE = CIE10.map(([codigo, descripcion]) => ({
  codigo,
  descripcion,
  clave: normalizar(`${codigo} ${descripcion}`),
}))

/** Busca por codigo ("j02") o por palabras en cualquier orden ("faring agud"). */
export function buscarCie10(consulta: string, limite = 8) {
  const q = normalizar(consulta)
  if (!q) return []
  const palabras = q.split(/\s+/)
  const codigoQ = q.replace(/\s+/g, '').toUpperCase()
  return INDICE.filter((d) => d.codigo.replace('.', '').startsWith(codigoQ.replace('.', '')) || palabras.every((p) => d.clave.includes(p)))
    .sort((a, b) => Number(b.codigo.toUpperCase().startsWith(codigoQ)) - Number(a.codigo.toUpperCase().startsWith(codigoQ)))
    .slice(0, limite)
}
